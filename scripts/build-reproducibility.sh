#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

mkdir -p reproducibility

echo "== Foundry compiler profile =="
forge config --json | tee reproducibility/forge-config.json >/dev/null

echo "== Build with build-info =="
forge build --build-info --sizes --force

BUILD_INFO_COUNT="$(find out/build-info -type f -name '*.json' 2>/dev/null | wc -l | tr -d ' ')"
if [[ "$BUILD_INFO_COUNT" == "0" ]]; then
  echo "No build-info JSON generated under out/build-info" >&2
  exit 1
fi

cat > reproducibility/README.md <<'MARKDOWN'
# Build Reproducibility Artifacts

Generated by:

```bash
scripts/build-reproducibility.sh
```

Review checklist:

- `foundry.toml` pins `solc_version = "0.8.35"`.
- `foundry.toml` pins `evm_version = "prague"`.
- `optimizer = true`, `optimizer_runs = 200`, `via_ir = true`.
- `out/build-info/*.json` exists after `forge build --build-info`.
- The deployed bytecode must be verified from the same commit and compiler
  profile before production install.

`reproducibility/` and `out/` are intentionally gitignored generated artifacts.
MARKDOWN

echo "Build-info files: $BUILD_INFO_COUNT"
echo "Wrote reproducibility/forge-config.json and reproducibility/README.md"
